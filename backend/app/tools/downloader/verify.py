"""Real integration check for the video downloader (inside worker-download, through the egress proxy).

    docker compose run --rm --no-deps worker-download python -m app.tools.downloader.verify

Stable public URLs chosen on 18/10/2026 (Wikimedia Commons, PUBLIC DOMAIN, NASA works):
- VIDEO_URL: "James Webb Space Telescope Launch and Orbit at L2", 10 s, several heights, no audio.
- AUDIO_URL: "Apollo 15 launch", 74 s, with audio.
Why: public, no login, no DRM, long-lived archive, and downloading them breaks no platform's terms.
"""

import json
import os
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from app.security.file_sniffing import sniff
from app.security.sandbox import Limits, run
from app.tools.downloader.extractor import YtDlpExtractor

VIDEO_URL = ("https://commons.wikimedia.org/wiki/File:"
             "James_Webb_Space_Telescope_Launch_and_Orbit_at_L2_(SVS4991_-_jwst_launch_1080p60).webm")
AUDIO_URL = "https://commons.wikimedia.org/wiki/File:Apollo_15_launch.ogv"
VERIFIED_FILE = Path(__file__).with_name("verified.json")
CAPABILITIES = ("url->mp4", "url->m4a", "url->mp3")


def verified_keys() -> set[str]:
    if not VERIFIED_FILE.exists():
        return set()
    return {e["key"] for e in json.loads(VERIFIED_FILE.read_text(encoding="utf-8")).get("passed", [])}


def _probe(path: Path) -> dict:
    out = run(["ffprobe", "-v", "error", "-print_format", "json", "-show_streams", "-show_format", str(path)],
              cwd=path.parent, limits=Limits(timeout_seconds=30))
    return json.loads(out)


def check(key: str, extractor: YtDlpExtractor, work: Path) -> dict:
    output = key.split("->")[1]
    if output == "mp4":
        info = extractor.inspect(VIDEO_URL)
        assert info.heights, "no real heights listed"
        target = 480 if 480 in info.heights else info.heights[0]
        path = extractor.download(VIDEO_URL, "mp4", str(target), work, lambda v: None)
        streams = _probe(path)["streams"]
        heights = [s.get("height", 0) for s in streams if s.get("codec_type") == "video"]
        assert heights and max(heights) <= target, f"height {heights} > requested {target}"
        detail = {"url": VIDEO_URL, "offered_heights": info.heights, "requested": target, "got": max(heights)}
    else:
        info = extractor.inspect(AUDIO_URL)
        assert info.has_audio, "source reports no audio"
        path = extractor.download(AUDIO_URL, output, "audio", work, lambda v: None)
        streams = _probe(path)["streams"]
        assert [s for s in streams if s.get("codec_type") == "audio"], "no audio stream in output"
        detail = {"url": AUDIO_URL}
    assert sniff(path, output).format == output, "output is not the promised format"
    return {**detail, "bytes": path.stat().st_size}


def main() -> None:
    extractor = YtDlpExtractor(proxy=os.environ.get("EGRESS_PROXY_URL"), max_bytes=300 * 1024 * 1024, max_seconds=1200)
    results = {"passed": [], "failed": []}
    for key in CAPABILITIES:
        with tempfile.TemporaryDirectory() as tmp:
            try:
                results["passed"].append({"key": key, **check(key, extractor, Path(tmp))})
            except Exception as exc:  # noqa: BLE001
                error = f"{type(exc).__name__}: {getattr(exc, 'message', exc)}"[:300]
                results["failed"].append({"key": key, "error": error})
    results["note"] = "Generated by app.tools.downloader.verify inside worker-download (via egress proxy)."
    results["run"] = datetime.now(UTC).isoformat(timespec="seconds")
    VERIFIED_FILE.write_text(json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"passed={len(results['passed'])} failed={len(results['failed'])}")
    for e in results["failed"]:
        print("FAILED", e["key"], e["error"])


if __name__ == "__main__":
    main()
